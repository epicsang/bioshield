# --------- Load all JSONs ---------
files = sorted(glob.glob(os.path.join(DATA_DIR, "*.json")))
rows = []

for f in files:
    try:
        with open(f, "r", encoding="utf-8") as fh:
            j = json.load(fh)
    except Exception:
        continue

    raw = json.dumps(j, ensure_ascii=False)
    meta = j.get("metadata", {}) if isinstance(j, dict) else {}
    sessions = j.get("biometricSessions") if isinstance(j, dict) else None
    session = sessions[0] if isinstance(sessions, list) and sessions else {}

    vuln_list        = j.get("vulnerabilities", []) if isinstance(j, dict) else []
    api_findings     = j.get("apiFindings", []) if isinstance(j, dict) else []
    crypto_findings  = j.get("cryptoFindings", []) if isinstance(j, dict) else []
    network_findings = j.get("networkFindings", []) if isinstance(j, dict) else []
    storage_findings = j.get("storageFindings", []) if isinstance(j, dict) else []
    memory_findings  = j.get("memoryFindings", []) if isinstance(j, dict) else []
    timing           = j.get("timingData", {}) if isinstance(j, dict) else {}

    # Derived flags from structured + raw text
    neg_btn = 0
    dep_api = 0
    for v in vuln_list:
        title = (v.get("title") or "").lower()
        cat   = (v.get("category") or "").lower()
        tech  = json.dumps(v.get("technicalDetails", {})).lower()
        if "negative button" in title or "negative" in title:
            neg_btn = 1
        if "deprecated" in cat or "fingerprintmanager" in tech:
            dep_api = 1

    if not dep_api and "fingerprintmanager" in raw.lower():
        dep_api = 1

    # Crypto present: prefer structured finding, else fall back to session.hasCrypto
    has_crypto = 1 if crypto_findings else int(bool(session.get("hasCrypto", False)))

    net_flag = 1 if network_findings else (1 if re.search(r"\b(post|fetch|http|https|socket\.send)\b", raw, re.I) else 0)
    tls_ok   = bool(re.search(r"TLSv1\.\d|TLSv2|cipher|pinning", raw, re.I))

    store_flag  = 1 if storage_findings else (1 if re.search(r"FileOutputStream|/sdcard|external|write\(", raw, re.I) else 0)
    hooked_flag = 1 if re.search(r"\bHOOKED\b|\bFrida\b|\bXposed\b|\blibfrida\b", raw, re.I) else 0

    attempts = timing.get("attempts", []) if isinstance(timing, dict) else []
    retry_count = len(attempts)
    durations = []
    for a in attempts:
        d = a.get("duration", 0) if isinstance(a, dict) else 0
        try:
            durations.append(float(d or 0))
        except:
            durations.append(0.0)
    avg_duration = float(np.mean(durations)) if durations else 0.0
    min_duration = float(np.min(durations)) if durations else 0.0

    # Older schema fallback
    try:
        durationMs = float(session.get("durationMs") or 0)
    except:
        durationMs = 0.0
    result = (session.get("result") or "").lower()

    rows.append({
        "file": os.path.basename(f),
        "scan_id": meta.get("scanId", os.path.basename(f)),
        "timestamp": meta.get("timestamp"),
        "api": session.get("api",""),
        "result": result,
        "hasCrypto": int(bool(has_crypto)),
        "durationMs": durationMs,
        "negative_button_flag": int(neg_btn),
        "deprecated_api_flag": int(dep_api),
        "network_flag": int(net_flag),
        "tls_ok_hint": int(tls_ok),
        "storage_flag": int(store_flag),
        "hooked_flag": int(hooked_flag),
        "retry_count": int(retry_count),
        "avg_duration": avg_duration,
        "min_duration": min_duration,
        "vuln_count": len(vuln_list),
        "has_vulnerabilities_block": int(bool(vuln_list)),
        "has_apiFindings_block": int(bool(api_findings)),
        "has_cryptoFindings_block": int(bool(crypto_findings)),
        "has_networkFindings_block": int(bool(network_findings)),
        "has_storageFindings_block": int(bool(storage_findings)),
        "has_memoryFindings_block": int(bool(memory_findings)),
        "raw": raw  # keep for reference if you want, remove for smaller output
    })

df = pd.DataFrame(rows)

