def compute_rule_score_safe(r):
    try:
        score = 0
        evidence = []

        if r.get('hooked_flag', 0):
            score += WEIGHTS.get('hooked', 0)
            evidence.append("HOOKED/Frida/Xposed detected")
        if r.get('negative_button_flag', 0):
            score += WEIGHTS.get('negative_button', 0)
            evidence.append("Negative button in BiometricPrompt")
        if r.get('deprecated_api_flag', 0):
            score += WEIGHTS.get('deprecated_api', 0)
            evidence.append("Deprecated Fingerprint API in use")
        if not r.get('hasCrypto', 1):
            score += WEIGHTS.get('no_crypto', 0)
            evidence.append("No CryptoObject / Keystore missing")
        if r.get('network_flag', 0) and not r.get('tls_ok_hint', 1):
            score += WEIGHTS.get('network_insecure', 0)
            evidence.append("Network transfer without TLS/pinning evidence")
        if r.get('storage_flag', 0):
            score += WEIGHTS.get('template_storage', 0)
            evidence.append("Possible on-disk template/storage write")

        fast_ms = r.get('min_duration', 0) or r.get('durationMs', 0)
        if fast_ms and isinstance(fast_ms, (int, float)) and fast_ms < 100:
            score += WEIGHTS.get('fast_duration', 0)
            evidence.append(f"Very fast timing ({fast_ms:.1f} ms)")
        if isinstance(r.get('retry_count', 0), (int, float)) and r.get('retry_count', 0) > 3:
            score += WEIGHTS.get('retry_excess', 0)
            evidence.append(f"Excessive retries: {r['retry_count']}")

        # Always return exactly two values
        return [min(100, score), "; ".join(evidence)]
    except Exception as e:
        # Always return a two-element fallback
        return [0, f"Error: {e}"]

# ---- guaranteed-safe assignment ----
df[['rule_score', 'evidence']] = pd.DataFrame(
    df.apply(lambda r: compute_rule_score_safe(r), axis=1).tolist(),
    index=df.index
)

